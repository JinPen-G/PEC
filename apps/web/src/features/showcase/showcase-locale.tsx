const reverse: Record<string, string> = {
  ...Object.fromEntries(
    Object.entries(TRADITIONAL_TO_SIMPLIFIED).map(([traditional, simplified]) => [simplified, traditional]),
  ),
  面: '面',
  回: '回',
  托: '托',
  复: '復',
  台: '臺',
  干: '乾',
  松: '松',
  钟: '鐘',
  谱: '譜',
  卫: '衛',
  系: '系',
  制: '制',
  只: '只',
  发: '發',
  布: '布',
};
function translate(source: string, locale: PlatformLocale) {
  if (!source.trim() || !/[\u3400-\u9fff]/.test(source)) return source;
  const simplified = traditionalToSimplified(source);
  if (locale === 'zh-Hans') return simplified;
  if (locale === 'zh-Hant')
    return [...simplified]
      .map((character) => reverse[character] ?? character)
      .join('')
      .replace(/復[製制]/g, '複製')
      .replace(/關系/g, '關係')
      .replace(/聯系/g, '聯繫')
      .replace(/頭發/g, '頭髮');
  const normalized = simplified.trim().replace(/\s+/g, ' ');
  return (
    english[normalized] ??
    normalized
      .replace(/选取/g, 'Select ')
      .replace(/成功执行调拨任务，共\s*(\d+)\s*辆车/, 'Transferred $1 vehicles')
      .replace(/照片占位/, ' photo placeholder')
  );
}
function localizeTree(node: ReactNode, locale: PlatformLocale): ReactNode {
  if (typeof node === 'string') return translate(node, locale);
  if (Array.isArray(node)) return Children.map(node, (child) => localizeTree(child, locale));
  if (!isValidElement(node)) return node;
  const element = node as ReactElement<Record<string, unknown>>;
  if (element.props['data-preserve-language']) return node;
  if (element.type === 'pre' || element.type === 'code' || typeof element.props.source === 'string')
    return node;
  const props: Record<string, unknown> = {};
  for (const key of [
    'children',
    'header',
    'sidebar',
    'label',
    'title',
    'placeholder',
    'aria-label',
    'description',
    'footer',
  ]) {
    const value = element.props[key];
    if (typeof value === 'string' || Array.isArray(value) || isValidElement(value))
      props[key] = localizeTree(value as ReactNode, locale);
  }
  return cloneElement(element, props);
}
export function LocalizedView({ children }: { children: ReactNode }) {
  const { locale } = usePlatformLocale();
  return <>{localizeTree(children, locale)}</>;
}
export function useShowcaseText() {
  const { locale } = usePlatformLocale();
  return useCallback((source: string) => translate(source, locale), [locale]);
}
