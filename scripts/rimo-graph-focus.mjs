export function focusRimoGraph(graph, groups = rimoGraphFocus) {
  const byId = new Map(graph.nodes.map((node) => [node.id, node]));
  const targets = new Map();
  const unique = (items, identity = (item) => JSON.stringify(item)) => [
    ...new Map(items.map((item) => [identity(item), item])).values(),
  ];
  const nodes = groups.map((definition) => {
    const members = definition.members.map((id) => {
      if (!byId.has(id) || targets.has(id)) throw new Error(`Invalid focus membership: ${id}`);
      targets.set(id, definition.id);
      return byId.get(id);
    });
    const base = members[0];
    const evidence = unique(members.flatMap((node) => node.evidence));
    const points = definition.points.flatMap((id) => {
      if (!definition.members.includes(id)) throw new Error(`Point outside focus group: ${id}`);
      const node = byId.get(id);
      const reading = node.keyPoints?.length
        ? node.keyPoints
        : [{ kind: 'rule', text: node.summary, evidence: [0] }];
      return reading.map((point) => ({
        ...point,
        evidence: point.evidence.map((index) =>
          evidence.findIndex((source) => JSON.stringify(source) === JSON.stringify(node.evidence[index])),
        ),
      }));
    });
    const prototypes = unique(members.flatMap((node) => node.prototypes));
    return {
      ...base,
      label: definition.label,
      type: definition.type,
      summary: definition.summary,
      aliases: unique(members.flatMap((node) => [node.label, ...(node.aliases ?? [])])).filter(
        (label) => label !== definition.label,
      ),
      topics: unique(members.flatMap((node) => node.topics)),
      requirements: unique(members.flatMap((node) => node.requirements)),
      evidence,
      keyPoints: unique(points),
      prototypes,
      coverage: prototypes.length ? 'partial' : 'none',
    };
  });
  for (const node of graph.nodes)
    if (!targets.has(node.id)) {
      targets.set(node.id, node.id);
      nodes.push({ ...node });
    }
  const groupedEdges = new Map();
  const internal = [];
  for (const edge of graph.edges) {
    const source = targets.get(edge.source),
      target = targets.get(edge.target);
    if (source === target) {
      const node = nodes.find((node) => node.id === source);
      node.evidence = unique([...node.evidence, ...edge.evidence]);
      node.requirements = unique([
        ...node.requirements,
        ...edge.evidence.map((proof) => proof.requirementId),
      ]);
      internal.push(edge.id);
      continue;
    }
    const key = `${source}/${edge.relation}/${target}`;
    const current = groupedEdges.get(key);
    if (current) {
      current.evidence = unique([...current.evidence, ...edge.evidence]);
      if (!current.reasons.includes(edge.reason)) current.reasons.push(edge.reason);
      if (!current.labels.includes(edge.label)) current.labels.push(edge.label);
    } else groupedEdges.set(key, { ...edge, source, target, labels: [edge.label], reasons: [edge.reason] });
  }
  const edges = [...groupedEdges.entries()].map(([key, { labels, reasons, ...edge }]) => ({
    ...edge,
    id: `focus-${createHash('sha256').update(key).digest('hex').slice(0, 16)}`,
    label: labels.length === 1 ? labels[0] : labels.join('；'),
    reason: reasons.join('\n\n'),
  }));
  return { graph: { ...graph, nodes, edges }, mapping: Object.fromEntries(targets), internalEdges: internal };
}
